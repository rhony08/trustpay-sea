"""Demo dataset seeder (Phase 7.3).

Idempotent: creates a demo admin + reporters, ~10 entities (incl. QRIS), ~20
published reports, a dispute in safe-harbor, and a mock gov-blacklisted account.
Run after `seed_banks`:

    python -m app.seeds.seed_demo
"""

from __future__ import annotations

import asyncio
import logging
import random
import uuid

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.security import hash_password
