    ("ID", "014", "Bank Central Asia Tbk", "883-****-811", EntityType.BANK_ACCOUNT, Scheme.BANK),
    ("ID", "002", "Bank Rakyat Indonesia", "402-****-119", EntityType.BANK_ACCOUNT, Scheme.BANK),
